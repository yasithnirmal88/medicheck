// ─── Helper: Build Trend Data ─────────────────────────────────────────────────
function trend(
  months: string[],
  values: number[],
  low: number,
  high: number,
): TrendDataPoint[] {
  return months.map((date, i) => ({
    date,
    value: values[i],
    referenceLow: low,
    referenceHigh: high,
  }))
}

